#!/usr/bin/env node
/*
 * 1. Generates src/larviva-illustrations.js from assets/icons/*.svg
 *    (colours are replaced by currentColor so the module can theme them).
 * 2. Exports each dataset as JSON for CMS import or a data-src endpoint.
 * 3. Pre-renders the module into index.html between the LARVIVA markers.
 *
 *   node scripts/build.js
 *
 * No dependencies. In production the CMS template would call the same
 * LarvivaJourney.renderModule() server-side (Node) or reproduce its markup.
 */
"use strict";

var fs = require("fs");
var path = require("path");

var rootDir = path.resolve(__dirname, "..");
var iconDir = path.join(rootDir, "assets/icons");
var dataDir = path.join(rootDir, "data");

// ── 1. Icons ──────────────────────────────────────────────────────────────
function cleanSvg(source) {
  var svg = source
    .replace(/<\?xml[\s\S]*?\?>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<defs>[\s\S]*?<\/defs>/g, "")
    .replace(/\s(id|data-name|class)="[^"]*"/g, "")
    .replace(/\sfill="(?!none)[^"]*"/g, "")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim();
  return svg.replace(/^<svg\b/, '<svg fill="currentColor" focusable="false" aria-hidden="true"');
}

var icons = {};
fs.readdirSync(iconDir).filter(function (f) { return /\.svg$/i.test(f); }).sort().forEach(function (file) {
  icons[file.replace(/\.svg$/i, "")] = cleanSvg(fs.readFileSync(path.join(iconDir, file), "utf8"));
});

var registry =
  "/*\n" +
  " * GENERATED by scripts/build.js from assets/icons/*.svg — do not edit by hand.\n" +
  " *\n" +
  " * ILLUSTRATION ASSETS: to change an icon, replace or add an SVG in\n" +
  " * assets/icons/ and run `npm run build`. Stages reference icons by file name\n" +
  " * (without .svg) in their `illustration` field. Files named placeholder-*\n" +
  " * are stand-ins drawn for the prototype and should be replaced with\n" +
  " * approved LARVIVA artwork.\n" +
  " */\n" +
  "(function (root) {\n" +
  "  var ICONS = " + JSON.stringify(icons, null, 2).replace(/\n/g, "\n  ") + ";\n\n" +
  '  if (typeof module === "object" && module.exports) {\n' +
  "    module.exports = ICONS;\n" +
  "  } else {\n" +
  "    root.LARVIVA_ILLUSTRATIONS = ICONS;\n" +
  "  }\n" +
  '})(typeof window !== "undefined" ? window : globalThis);\n';
fs.writeFileSync(path.join(rootDir, "src/larviva-illustrations.js"), registry);
console.log("wrote src/larviva-illustrations.js (" + Object.keys(icons).length + " icons)");

// ── 2. JSON export ────────────────────────────────────────────────────────
fs.readdirSync(dataDir).filter(function (f) { return /^larviva-journey\.[\w-]+\.js$/.test(f); }).forEach(function (file) {
  var data = require(path.join(dataDir, file));
  var out = path.join(dataDir, file.replace(/\.js$/, ".json"));
  fs.writeFileSync(out, JSON.stringify(data, null, 2) + "\n");
  console.log("wrote " + path.relative(rootDir, out));
});

// ── 3. Pre-render ─────────────────────────────────────────────────────────
var journey = require(path.join(rootDir, "src/larviva-journey.js"));
var data = require(path.join(dataDir, "larviva-journey.en.js"));
var html = journey.renderModule(journey.prepare(data), {
  interactive: false,
  illustrations: icons,
  uid: "lj-static"
});

var indexPath = path.join(rootDir, "index.html");
var page = fs.readFileSync(indexPath, "utf8");
var pattern = /(<!-- LARVIVA:START -->)[\s\S]*?(<!-- LARVIVA:END -->)/;
if (!pattern.test(page)) {
  console.error("index.html is missing the LARVIVA:START / LARVIVA:END markers");
  process.exit(1);
}
fs.writeFileSync(indexPath, page.replace(pattern, function (m, start, end) {
  return start + "\n" + html + "\n" + end;
}));
console.log("pre-rendered module into index.html");
